#ifndef FOOTPRINT_CPPUTEST_GENERATED_CONFIG_H_
#define FOOTPRINT_CPPUTEST_GENERATED_CONFIG_H_

// ----------------------------------------------------------------------------

// The configuration of CppUTest for the footprint benchmark, in place of the
// one generated by the CppUTest build. It is included by
// `CppUTest/CppUTestGeneratedConfig.h` when `HAVE_CONFIG_H` is defined.
//
// With exceptions, the default configuration is kept. Without exceptions,
// CppUTest builds only without the standard C++ library, and its leak
// detection does not build without the standard C++ library, so both are
// disabled.

// ----------------------------------------------------------------------------

#if !defined(__cpp_exceptions)
#define CPPUTEST_STD_CPP_LIB_DISABLED
#define CPPUTEST_MEM_LEAK_DETECTION_DISABLED
#endif // !defined(__cpp_exceptions)

// ----------------------------------------------------------------------------

#endif // FOOTPRINT_CPPUTEST_GENERATED_CONFIG_H_

// ----------------------------------------------------------------------------
